"""Build sample bundles (ARCHITECTURE.md §6.2-§6.3, §10).

``simulated_scenario`` (P0, always built):
  The preferred real base (a 21-day validation/test window from the iAWE split) needs
  ``ml/split.py`` and the data audit, which are not implemented yet. Per the mandatory
  fallback in §10.2, the bundle therefore uses a fully synthetic background plus the
  deterministic synthetic appliance traces. No real data is padded, shifted or relabelled.

``typical_period``:
  Built only when at least one real appliance model has ``go``. Today no model has been
  evaluated, so it is not built and any stale bundle is removed.

Usage: python ml/make_samples.py [--artifacts DIR]
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import numpy as np

import common  # noqa: F401  (puts backend/ on sys.path)
from common import (
    ARTIFACTS_DIR,
    SCENARIO_PATH,
    config_sha256,
    load_scenario,
    repo_relative,
    window_csv_bytes,
    write_bytes,
    write_json,
)
from synthetic.generate import generate_trace
from synthetic.generate_background import generate_background

from app.analytics.constants import WINDOW_DAYS, WINDOW_MINUTES
from app.analytics.wording import assert_clean
from app.ingest.bundle import load_bundle, sha256_file
from app.nilm.preprocess import window_start
from app.nilm.registry import load_registry

GENERATE_SCRIPT = "ml/synthetic/generate.py"
BACKGROUND_SCRIPT = "ml/synthetic/generate_background.py"

DESCRIPTION = (
    "Fully simulated demonstration. The household background load and the appliance traces "
    "are generated by documented scripts with fixed seeds; they are not measurements of a real "
    "home. In the current week the simulated air conditioner runs longer each day and the "
    "simulated water heater draws more power while running."
)
COMPOSITION = (
    "fully_synthetic: aggregate.csv = synthetic background + sum(synthetic appliance traces); "
    "real-model inference is disabled for this bundle."
)
BASE_SELECTION_NOTE = (
    "No validated 21-day validation/test window from real data is available yet (data audit and "
    "split not run), so the mandatory fully synthetic fallback is used (ARCHITECTURE.md §10.2)."
)


def build_simulated_scenario(artifacts: Path, scenario_path: Path = SCENARIO_PATH) -> Path:
    scenario = load_scenario(scenario_path)
    if scenario["window"]["days"] != WINDOW_DAYS:
        raise ValueError(f"scenario window must be {WINDOW_DAYS} days")
    start = window_start(scenario["window"]["start"])
    days = scenario["window"]["days"]
    config_hash = config_sha256(scenario_path)
    config_rel = repo_relative(scenario_path)

    out = artifacts / "samples" / "simulated_scenario"
    if out.exists():
        shutil.rmtree(out)

    background = generate_background(scenario["background"], days)
    aggregate = background.copy()
    synthetic_meta = []
    seen_classes = set()
    for appliance in scenario["appliances"]:
        if appliance["class"] in seen_classes:
            raise ValueError(f"two monitored appliances share class {appliance['class']}")
        seen_classes.add(appliance["class"])
        trace = generate_trace(appliance, days)
        assert trace.size == WINDOW_MINUTES
        aggregate = aggregate + trace
        rel = f"synthetic/{appliance['id']}.csv"
        write_bytes(out / rel, window_csv_bytes(start, trace))
        synthetic_meta.append(
            {
                "id": appliance["id"],
                "trace": rel,
                "generator": {
                    "script": GENERATE_SCRIPT,
                    "config": config_rel,
                    "config_sha256": config_hash,
                    "seed": int(appliance["seed"]),
                },
                "expected_status": appliance["expected_status"],
            }
        )

    aggregate = np.round(aggregate, 1)
    write_bytes(out / "aggregate.csv", window_csv_bytes(start, aggregate))

    manifest = {
        "schema_version": 1,
        "sample_id": "simulated_scenario",
        "title": "Simulated scenario",
        "description": assert_clean(DESCRIPTION),
        "simulated": True,
        "window": {"start": start.isoformat(), "days": days},
        "aggregate_origin": "fully_synthetic",
        "real_base": None,
        "synthetic_background": {
            "script": BACKGROUND_SCRIPT,
            "config": config_rel,
            "config_sha256": config_hash,
            "seed": int(scenario["background"]["seed"]),
        },
        "synthetic_appliances": synthetic_meta,
        "composition": COMPOSITION,
        "base_selection_note": BASE_SELECTION_NOTE,
        "aggregate_sha256": sha256_file(out / "aggregate.csv"),
    }
    write_json(out / "manifest.json", manifest)
    load_bundle(out)  # the server's own validation must accept what we wrote
    return out


def handle_typical_period(artifacts: Path) -> str:
    out = artifacts / "samples" / "typical_period"
    registry_path = artifacts / "registry.json"
    go_models = []
    if registry_path.is_file():
        registry = load_registry(registry_path)
        go_models = [e.id for e in registry.entries.values() if e.provenance == "real_model" and e.status == "go"]
    if not go_models:
        if out.exists():
            shutil.rmtree(out)
        return "typical_period not built: no real appliance model has a go decision"
    raise NotImplementedError(
        f"go models {go_models} exist but real-base sample building needs ml/split.py (T-102); "
        "implement it before building typical_period"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--artifacts", type=Path, default=ARTIFACTS_DIR)
    args = parser.parse_args()
    out = build_simulated_scenario(args.artifacts)
    manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    print(f"wrote {out} (aggregate_sha256={manifest['aggregate_sha256'][:12]}…)")
    print(handle_typical_period(args.artifacts))


if __name__ == "__main__":
    main()
