"""Synthetic-data PROTOTYPE: train a sequence-to-point model for the air conditioner.

    python ml/prototype_synthetic/train.py

What it does:
1. Generates randomized simulated households (``households.py``): train, validation and
   test households use disjoint seeds.
2. Trains a sequence-to-point neural network (scikit-learn ``MLPRegressor``): input = 99
   minutes of normalized aggregate power, output = AC power at the centre minute.
3. Exports it to ONNX and evaluates it on the held-out test households THROUGH THE SERVING
   ADAPTER (``app.nilm.adapters.onnx_seq2point``), against the naive baseline
   (aggregate × training share), with the metric definitions of ARCHITECTURE.md §12.4.
4. Writes ``ml/prototype_synthetic/report.json`` and ``ml/out/prototype_synthetic/model.onnx``.

What it is NOT: evidence about real homes. The model learns patterns of data we generated
ourselves. It is not registered, not served by the app, and its numbers must never be
presented as real-world accuracy. The real path is the iAWE pipeline (T-101…T-405).
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # ml/
import common  # noqa: E402,F401  (puts backend/ on sys.path)
from common import REPO_ROOT, write_bytes, write_json  # noqa: E402
from prototype_synthetic.households import household  # noqa: E402

from app.nilm.adapters.onnx_seq2point import OnnxSeq2PointAdapter  # noqa: E402

WINDOW = 99
HALF = WINDOW // 2
ON_THRESHOLD_W = 150.0
TRAIN_SEEDS = list(range(1000, 1008))
VALIDATION_SEEDS = [2000, 2001]
TEST_SEEDS = [3000, 3001, 3002]
TRAIN_STRIDE = 2  # use every 2nd window to keep memory and training time small
HIDDEN_LAYERS = (128, 64)
OUT_DIR = REPO_ROOT / "ml" / "out" / "prototype_synthetic"
REPORT_PATH = REPO_ROOT / "ml" / "prototype_synthetic" / "report.json"
LABEL = (
    "Prototype trained and tested on simulated households generated by our own scripts. "
    "Not evaluated on real data, not registered or served by the app, and not evidence of "
    "accuracy in real homes."
)


def windows(aggregate: np.ndarray, stride: int = 1) -> np.ndarray:
    return np.lib.stride_tricks.sliding_window_view(aggregate, WINDOW)[::stride]


def metrics(pred: np.ndarray, actual: np.ndarray) -> dict:
    """§12.4 definitions on minutes where the prediction exists. Undefined -> None."""
    valid = ~np.isnan(pred) & ~np.isnan(actual)
    p, a = pred[valid], actual[valid]
    if a.size == 0:
        return {"mae_w": None, "onoff_f1": None}
    mae = float(np.abs(p - a).mean())
    on_p, on_a = p >= ON_THRESHOLD_W, a >= ON_THRESHOLD_W
    tp = int((on_p & on_a).sum())
    fp = int((on_p & ~on_a).sum())
    fn = int((~on_p & on_a).sum())
    f1 = 2 * tp / (2 * tp + fp + fn) if (2 * tp + fp + fn) else None
    return {"mae_w": round(mae, 2), "onoff_f1": None if f1 is None else round(f1, 4)}


def weekly_errors(pred: np.ndarray, actual: np.ndarray) -> list[dict]:
    out = []
    for week in range(actual.size // (7 * 1440)):
        sl = slice(week * 7 * 1440, (week + 1) * 7 * 1440)
        p, a = pred[sl], actual[sl]
        valid = ~np.isnan(p)
        actual_kwh = a[valid].mean() * 168 / 1000 if valid.any() else None
        pred_kwh = p[valid].mean() * 168 / 1000 if valid.any() else None
        err = None if not actual_kwh else abs(pred_kwh - actual_kwh) / actual_kwh * 100
        out.append({"week": week + 1, "actual_kwh": _r(actual_kwh), "predicted_kwh": _r(pred_kwh), "error_pct": _r(err)})
    return out


def _r(x):
    return None if x is None else round(float(x), 2)


def summarize(per_house: list[tuple[np.ndarray, np.ndarray]]) -> dict:
    pred = np.concatenate([p for p, _ in per_house])
    actual = np.concatenate([a for _, a in per_house])
    weeks = [w for p, a in per_house for w in weekly_errors(p, a)]
    errs = [w["error_pct"] for w in weeks if w["error_pct"] is not None]
    return {
        **metrics(pred, actual),
        "weekly_energy_error_pct": {
            "median": _r(np.median(errs)) if errs else None,
            "worst": _r(max(errs)) if errs else None,
        },
        "weeks": weeks,
    }


def main() -> None:
    from skl2onnx import to_onnx
    from sklearn.neural_network import MLPRegressor

    started = time.time()
    train = [household(s) for s in TRAIN_SEEDS]
    agg_train = np.concatenate([a for a, _ in train])
    ac_train = np.concatenate([ac for _, ac in train])
    norm = {
        "mains_mean": float(agg_train.mean()),
        "mains_std": float(agg_train.std()),
        "app_mean": float(ac_train.mean()),
        "app_std": float(ac_train.std()),
    }
    share = float(ac_train.sum() / agg_train.sum())  # naive baseline: ratio of sums over train

    X = np.vstack([windows(a, TRAIN_STRIDE) for a, _ in train])
    y = np.concatenate([ac[HALF : HALF + windows(a).shape[0]][::TRAIN_STRIDE] for a, ac in train])
    X = ((X - norm["mains_mean"]) / norm["mains_std"]).astype(np.float32)
    y = ((y - norm["app_mean"]) / norm["app_std"]).astype(np.float32)

    model = MLPRegressor(
        hidden_layer_sizes=HIDDEN_LAYERS, activation="relu", solver="adam", batch_size=512,
        learning_rate_init=1e-3, max_iter=40, early_stopping=True, validation_fraction=0.1,
        n_iter_no_change=5, random_state=0,
    )
    model.fit(X, y)
    train_seconds = time.time() - started

    onnx_model = to_onnx(model, X[:1], target_opset=17)
    model_path = OUT_DIR / "model.onnx"
    write_bytes(model_path, onnx_model.SerializeToString())
    adapter = OnnxSeq2PointAdapter.from_file(model_path, WINDOW, norm)

    def evaluate(seeds):
        model_runs, naive_runs = [], []
        for seed in seeds:
            aggregate, ac = household(seed)
            model_runs.append((adapter.predict(aggregate), ac))  # the serving inference path
            naive = aggregate * share
            naive[:HALF], naive[-HALF:] = np.nan, np.nan  # score the same minutes as the model
            naive_runs.append((naive, ac))
        return {"model": summarize(model_runs), "naive": summarize(naive_runs)}

    # Parity: scikit-learn prediction vs the ONNX serving adapter on one held-out household.
    aggregate, _ = household(TEST_SEEDS[0])
    sk = model.predict(((windows(aggregate) - norm["mains_mean"]) / norm["mains_std"]).astype(np.float32))
    sk_w = sk * norm["app_std"] + norm["app_mean"]
    served = adapter.predict(aggregate)[HALF : HALF + sk_w.size]
    parity = float(np.abs(served - sk_w).max())

    report = {
        "label": LABEL,
        "model": {
            "type": "sequence-to-point MLPRegressor (scikit-learn), exported to ONNX",
            "hidden_layers": list(HIDDEN_LAYERS),
            "window_minutes": WINDOW,
            "target": "air conditioner (simulated)",
            "onnx_path": "ml/out/prototype_synthetic/model.onnx (not committed; regenerate with this script)",
            "norm": {k: round(v, 4) for k, v in norm.items()},
            "naive_share": round(share, 6),
            "on_threshold_w": ON_THRESHOLD_W,
            "training_iterations": int(model.n_iter_),
            "training_seconds": round(train_seconds, 1),
            "training_windows": int(X.shape[0]),
        },
        "data": {
            "source": "simulated households (ml/prototype_synthetic/households.py)",
            "days_per_household": 21,
            "train_seeds": TRAIN_SEEDS,
            "validation_seeds": VALIDATION_SEEDS,
            "test_seeds": TEST_SEEDS,
        },
        "parity": {"max_abs_diff_w": round(parity, 6), "tolerance_w": 1.0, "passed": parity <= 1.0},
        "validation": evaluate(VALIDATION_SEEDS),
        "test": evaluate(TEST_SEEDS),
    }
    write_json(REPORT_PATH, report)
    t, n = report["test"]["model"], report["test"]["naive"]
    print(LABEL)
    print(f"trained in {train_seconds:.0f}s ({model.n_iter_} iterations, {X.shape[0]} windows); parity max diff {parity:.6f} W")
    print(f"TEST (simulated) model: MAE {t['mae_w']} W, weekly energy error median {t['weekly_energy_error_pct']['median']}%, F1 {t['onoff_f1']}")
    print(f"TEST (simulated) naive: MAE {n['mae_w']} W, weekly energy error median {n['weekly_energy_error_pct']['median']}%, F1 {n['onoff_f1']}")
    print(f"wrote {REPORT_PATH.relative_to(REPO_ROOT)} and {model_path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
